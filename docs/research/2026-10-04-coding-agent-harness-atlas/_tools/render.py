_UNSAFE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f-\x9f\ud800-\udfff‪-‮⁦-⁩]")
_BAD_URL_CHARS = re.compile(r"[\s\x00-\x1f\x7f-\x9f\\]")
_DATE = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$")


class RenderError(Exception):
    """Bad input or a breached limit: reported on stderr, exit 2."""


# --- text, links ---------------------------------------------------------------------------


def clean(value):
    """Text safe to emit: LF only; lone surrogates, controls and bidi overrides become U+FFFD."""
    text = "" if value is None else str(value)
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    return _UNSAFE.sub("�", text)


def esc(value):
    return html.escape(clean(value), quote=True)


def clip(text, limit=CLIP):
    return text if len(text) <= limit else text[:limit] + "…"


def safe_external(url, hosts):
    """True only for an https URL whose host is exactly one of ``hosts`` (no userinfo, no port)."""
    if not isinstance(url, str) or not url.startswith("https://") or _BAD_URL_CHARS.search(url):
        return False
    try:
        parts = urlsplit(url)
        host = parts.hostname
    except ValueError:
        return False
    return bool(host) and host in hosts and parts.netloc.lower() == host


def rel(src, dst):
    return posixpath.relpath(dst, posixpath.dirname(src) or ".")


def href(src, dst, fragment=None):
    base = "" if dst == src and fragment else rel(src, dst)
    if fragment is None:
        return esc(base)
    return esc(f"{base}#{quote(fragment, safe='/.-_:')}")


def local_link(src, dst, text, fragment=None):
    return f'<a href="{href(src, dst, fragment)}">{esc(text)}</a>'


def time_html(date):
    text = clean(date)
    if _DATE.match(text):
        return f'<time datetime="{text}">{text}</time>'
    return esc(text)


def as_list(value):
    return value if isinstance(value, list) else []


def as_dict(value):
    return value if isinstance(value, dict) else {}


def lever_key(surface, lever, model):
    model = "" if model is None else str(model)
    if model.lower() in NULL_MODEL_TOKENS:
        model = ""
    return f"{surface}|{lever}|{model}"


def ref_key(ref):
    parts = str(ref).split("|")
    if len(parts) != 3:
        return str(ref)
    return lever_key(*parts)


def ordered(known, present):
    """``known`` order first, then anything else in ``present`` sorted: nothing is dropped."""
    seen = []
    for item in list(known) + sorted(set(present) - set(known)):
        if item in present and item not in seen:
            seen.append(item)
    return seen


# --- data ------------------------------------------------------------------------------------


def scan_forbidden(obj, where):
    if isinstance(obj, dict):
        for key in obj:
            if str(key).lower() in FORBIDDEN_KEYS:
                raise RenderError(f"numeric-confidence key '{key}' in {where}; none is allowed")
            scan_forbidden(obj[key], where)
    elif isinstance(obj, list):
        for item in obj:
            scan_forbidden(item, where)


def _read(path, required):
    if not path.exists():
        if required:
            raise RenderError(f"{path} is required and missing")
        return None
    try:
        return load_json(path)
    except (OSError, ValueError) as exc:
        raise RenderError(f"{path}: {exc}") from exc


def _records(doc, key, path):
    if doc is None:
        return []
    items = doc.get(key, []) if isinstance(doc, dict) else None
    if not isinstance(items, list) or not all(isinstance(i, dict) for i in items):
        raise RenderError(f"{path}: expected an object whose '{key}' is a list of objects")
    return items


def _check_state(item, what):
    if item.get("state") not in STATE_INFO:
        raise RenderError(f"{what} has an unknown state {item.get('state')!r}")
    if item.get("verification") not in VERIFICATIONS:
        raise RenderError(f"{what} has an unknown verification {item.get('verification')!r}")


class Atlas:
    """The loaded data plus the indexes the pages need."""

    def __init__(self, data_dir):
        data_dir = Path(data_dir)
        facets_doc = _read(data_dir / "facets.json", True)
        surfaces_doc = _read(data_dir / "surfaces.json", True)
        self.surfaces = _records(surfaces_doc, "surfaces", data_dir / "surfaces.json")
        for surface in self.surfaces:
            if not surface.get("id"):
                raise RenderError("surfaces.json: a surface has no id")
        self.surface_ids = [s["id"] for s in self.surfaces]
        self.surface = {s["id"]: s for s in self.surfaces}
        self.lever_classes = as_list(facets_doc.get("lever_classes"))
        main_facets = _records(facets_doc, "facets", data_dir / "facets.json")
        optional = [
            f
            for f in _records(facets_doc, "optional_facets", data_dir / "facets.json")
            if f.get("rows")
        ]
        self.facets = main_facets + optional
        self.rows = {}
        for facet in self.facets:
            for row in as_list(facet.get("rows")):
                self.rows[row.get("id")] = facet
        self.row_ids = list(self.rows)

        self.products = []
        self.product_surfaces = {}
        for surface in self.surfaces:
            pid = surface.get("parent_product") or surface["id"]
            if pid not in self.product_surfaces:
                self.product_surfaces[pid] = []
                self.products.append(pid)
            self.product_surfaces[pid].append(surface)
        self.product_of = {s["id"]: (s.get("parent_product") or s["id"]) for s in self.surfaces}
        self.hosts = tuple(
            sorted(
                {str(h).lower() for s in self.surfaces for h in as_list(s.get("docs_hosts"))}
                | set(EXTRA_HOSTS)
            )
        )

        self.cells = {}
        self.unmapped = {sid: [] for sid in self.surface_ids}
        self.evidence = {}
        self.evidence_by_surface = {}
        for sid in self.surface_ids:
            path = data_dir / "cells" / f"{sid}.json"
            for cell in _records(_read(path, False), "cells", path):
                scan_forbidden(cell, f"cell {cell.get('id')}")
                _check_state(cell, f"cell {cell.get('id')}")
                if cell.get("row") == "U00":
                    self.unmapped[sid].append(cell)
                else:
                    self.cells.setdefault((sid, cell.get("row")), cell)
            path = data_dir / "evidence" / f"{sid}.json"
            records = _records(_read(path, False), "evidence", path)
            for record in records:
                scan_forbidden(record, f"evidence {record.get('id')}")
                self.evidence.setdefault(record.get("id"), record)
            self.evidence_by_surface[sid] = records

        levers_doc = _read(data_dir / "levers.json", False)
        lever_path = data_dir / "levers.json"
        self.levers = _records(levers_doc, "levers", lever_path)
        self.task_rows = []
        if isinstance(levers_doc, dict) and "task_shape_rows" in levers_doc:
            self.task_rows = _records(levers_doc, "task_shape_rows", lever_path)
        for lever in self.levers:
            scan_forbidden(lever, f"lever {lever.get('surface')}/{lever.get('lever')}")
            _check_state(lever, f"lever {lever.get('surface')}/{lever.get('lever')}")
        for task in self.task_rows:
            scan_forbidden(task, f"task-shape row {task.get('surface')}/{task.get('task_class')}")
        self.levers_by_cell = {}
        self.lever_anchor = {}
        self.lever_literals = {}
        for index, lever in enumerate(self.levers):
            cell_key = (lever.get("surface"), lever.get("row"))
            self.levers_by_cell.setdefault(cell_key, []).append(lever)
            key = lever_key(lever.get("surface"), lever.get("lever"), lever.get("model"))
            self.lever_anchor.setdefault(key, f"lever-{index}")
            literal = lever.get("literal")
            if isinstance(literal, str) and literal:
                found = self.lever_literals.setdefault(key, [])
                if literal not in found:
                    found.append(literal)

        register_path = data_dir / "register.json"
        entries = _records(_read(register_path, False), "entries", register_path)
        self.register = sorted(
            entries,
            key=lambda e: (
                not isinstance(e.get("rank"), int),
                e.get("rank") if isinstance(e.get("rank"), int) else 0,
                str(e.get("id")),
            ),
        )
        self.register_by_cell = {}
        for entry in self.register:
            for cell_id in as_list(entry.get("cells")):
                self.register_by_cell.setdefault(cell_id, []).append(entry)

        snapshot = _read(data_dir / "snapshot.json", False)
        self.snapshot = snapshot if isinstance(snapshot, dict) else {}
        self.columns = {}
        for column in as_list(self.snapshot.get("columns")):
            if isinstance(column, dict):
                self.columns.setdefault(column.get("surface"), column)

    def harness_path(self, sid):
        return f"harness/{self.product_of[sid]}.html"

    def product_name(self, pid):
        return PRODUCT_NAMES.get(pid) or clean(self.product_surfaces[pid][0].get("name") or pid)

    def surface_name(self, sid):
        return clean(self.surface[sid].get("name") or sid) if sid in self.surface else clean(sid)


