def heading(level, text, anchor=None):
    ident = f' id="{esc(anchor)}"' if anchor else ""
    return f"<h{level}{ident}>{esc(text)}</h{level}>"


def th(content, scope="col"):
    return f'<th scope="{scope}">{content}</th>'


def td(content, cls=""):
    return f'<td class="{cls}">{content}</td>' if cls else f"<td>{content}</td>"


def table(caption, head, rows, cls=""):
    """``head`` and each row's cells are ready HTML; a row is (anchor or None, [cells])."""
    klass = f' class="{cls}"' if cls else ""
    out = [
        f'<div class="scroll" tabindex="0" role="region" aria-label="{esc(caption)}">',
        f"<table{klass}>",
        f"<caption>{esc(caption)}</caption>",
        "<thead><tr>" + "".join(head) + "</tr></thead>",
        "<tbody>",
    ]
    for anchor, cells in rows:
        ident = f' id="{esc(anchor)}"' if anchor else ""
        out.append(f"<tr{ident}>" + "".join(cells) + "</tr>")
    out += ["</tbody>", "</table>", "</div>"]
    return "\n".join(out)


