def render_all(data_dir):
    """Every page as {relative path: text}, in a fixed order."""
    atlas = Atlas(data_dir)
    pages = {"index.html": render_index(atlas), "matrix.html": render_matrix(atlas)}
    for pid in atlas.products:
        pages[f"harness/{pid}.html"] = render_harness(atlas, pid)
    pages["levers.html"] = render_levers(atlas)
    pages["register.html"] = render_register(atlas)
    for sid in atlas.surface_ids:
        pages[f"sources/{sid}.html"] = render_sources(atlas, sid)
    pages["method.html"] = render_method(atlas)
    return pages


def encode_pages(pages):
    encoded = {}
    for path, text in pages.items():
        try:
            encoded[path] = text.encode("utf-8")
        except UnicodeEncodeError as exc:
            raise RenderError(f"{path} is not encodable as UTF-8: {exc}") from exc
    return encoded


def check_sizes(encoded):
    problems = [
        f"page {path} is {len(data)} bytes, over the {MAX_PAGE_BYTES} limit"
        for path, data in encoded.items()
        if len(data) > MAX_PAGE_BYTES
    ]
    total = sum(len(d) for d in encoded.values())
    if total > MAX_TOTAL_BYTES:
        problems.append(f"all pages together are {total} bytes, over the {MAX_TOTAL_BYTES} limit")
    if problems:
        raise RenderError("; ".join(problems))


def extra_pages(out, rendered):
    """``*.html`` files in the output folder, harness/ and sources/ that no page of ours maps to."""
    found = []
    for folder in ("", "harness", "sources"):
        directory = out / folder if folder else out
        if directory.is_dir():
            for path in sorted(directory.glob("*.html")):
                name = f"{folder}/{path.name}" if folder else path.name
                if name not in rendered and path.is_file():
                    found.append(name)
    return found


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data-dir", default=str(DATA_DIR))
    parser.add_argument("--out", default=str(ATLAS_DIR))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if not args.check:  # --check only reads, so it also runs on main after the branch lands
        assert_worktree()
    try:
        encoded = encode_pages(render_all(args.data_dir))
        check_sizes(encoded)
    except RenderError as exc:
        print(f"render: {exc}", file=sys.stderr)
        return 2
    out = Path(args.out)
    extras = extra_pages(out, encoded)
    if args.check:
        bad = []
        for path, data in encoded.items():
            target = out / path
            if not target.is_file():
                bad.append(f"missing: {path}")
            elif target.read_bytes() != data:
                bad.append(f"stale: {path}")
        for line in bad:
            print(f"render: {line}", file=sys.stderr)
        for path in extras:
            print(f"render: extra: {path} is not a page the renderer writes", file=sys.stderr)
        if bad:
            print(f"render: {len(bad)} of {len(encoded)} pages out of date", file=sys.stderr)
        if extras:
            print(f"render: {len(extras)} extra page(s) in the output folder", file=sys.stderr)
        if bad or extras:
            return 1
        print(f"render: {len(encoded)} pages up to date")
        return 0
    for path, data in encoded.items():
        target = out / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    print(f"render: wrote {len(encoded)} pages ({sum(len(d) for d in encoded.values())} bytes)")
    for path in extras:
        print(
            f"render: warning: extra page {path} is not written by the renderer; "
            "it was left in place, delete it or restore its data",
            file=sys.stderr,
        )
    return 1 if extras else 0


if __name__ == "__main__":
    sys.exit(main())
