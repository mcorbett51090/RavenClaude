def document(page, title, h1, body):
    """Wrap a page body: doctype, generated marker, CSP, nav, skip link, optional age script."""
    script = ""
    csp_script = ""
    if "<time " in body:
        digest = base64.b64encode(bytes.fromhex(sha256_bytes(AGE_SCRIPT.encode("utf-8"))))
        csp_script = f"script-src 'sha256-{digest.decode('ascii')}'; "
        script = f"<script>{AGE_SCRIPT}</script>\n"
    csp = (
        "default-src 'none'; style-src 'unsafe-inline'; "
        f"{csp_script}img-src data:; base-uri 'none'; form-action 'none'"
    )
    nav = "".join(
        f'<li><a href="{href(page, dst)}"'
        + (' aria-current="page"' if dst == page else "")
        + f">{esc(label)}</a></li>"
        for dst, label in NAV
    )
    return (
        "\n".join(
            [
                "<!DOCTYPE html>",
                GENERATED,
                '<html lang="en">',
                "<head>",
                '<meta charset="utf-8">',
                f'<meta http-equiv="Content-Security-Policy" content="{csp}">',
                '<meta name="viewport" content="width=device-width, initial-scale=1">',
                '<meta name="color-scheme" content="light dark">',
                f"<title>{esc(title if title == ATLAS_TITLE else f'{title} | {ATLAS_TITLE}')}</title>",
                f"<style>{CSS}</style>",
                "</head>",
                "<body>",
                '<a class="skip" href="#main">Skip to content</a>',
                f'<header><nav aria-label="Atlas pages"><ul>{nav}</ul></nav></header>',
                '<main id="main">',
                f"<h1>{esc(h1)}</h1>",
                body,
                "</main>",
                script + "</body>",
                "</html>",
            ]
        )
        + "\n"
    )


def matrix_cell(atlas, sid, row_id, page):
    cell = atlas.cells.get((sid, row_id))
    target = href(page, atlas.harness_path(sid), f"{sid}/{row_id}")
