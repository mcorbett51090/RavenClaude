def ext_link(url, atlas):
    if safe_external(url, atlas.hosts):
        return f'<a href="{esc(url)}">{esc(url)}</a>'
    return f'<span class="mono">{esc(url)}</span>'


def evidence_link(eid, atlas, page):
    record = atlas.evidence.get(eid)
    if record is None or record.get("surface") not in atlas.surface:
        return f'<span class="mono">{esc(eid)}</span> <span class="nodata">(no record)</span>'
    target = f"sources/{record['surface']}.html"
    return f'<a class="mono" href="{href(page, target, clean(eid))}">{esc(eid)}</a>'


def citation_line(record, atlas):
    version = record.get("product_version")
    parts = [
        f"Source: {ext_link(record.get('url'), atlas)}",
        f"retrieved {time_html(record.get('retrieved'))}",
        "version " + (esc(version) if version else "not recorded"),
        f"tier {esc(record.get('tier'))}",
    ]
    return '<p class="cite">' + "; ".join(parts) + "</p>"


def locator_text(record):
    loc = record.get("locator") if isinstance(record.get("locator"), dict) else {}
    lines = f"raw lines {loc.get('raw_line_start')}-{loc.get('raw_line_end')}"
    return f"{loc['heading']}, {lines}" if loc.get("heading") else lines


def span_note(record):
    span = record.get("described_span")
    if not isinstance(span, dict):
        return None
    lines = f"raw lines {span.get('raw_line_start')}-{span.get('raw_line_end')}"
    return f"Described span: {clean(span.get('description'))} ({lines})"


def split_refs(refs, limit=MAX_HARNESS_QUOTES):
    """The refs a harness page quotes, and the rest it leaves to the sources page.

    Within the budget the order is kept. Past it, the role-labelled records (the vendor statement,
    the reference page, the positive quote) are the ones the cell rests on, so they are kept first.
    """
    if len(refs) <= limit:
        return refs, []
    ranked = sorted(refs, key=lambda ref: ref[0] is None)
    return ranked[:limit], ranked[limit:]


def evidence_block(eid, role, atlas, page):
    record = atlas.evidence.get(eid)
    label = f"<strong>{esc(role)}:</strong> " if role else ""
    if record is None:
        return f"<li>{label}{evidence_link(eid, atlas, page)}</li>"
    quote_text = clean(record.get("quote"))
    note = span_note(record)
    if quote_text:
        body = f"<blockquote><p>{esc(quote_text)}</p></blockquote>"
    elif note:
        body = f"<p>{esc(note)}</p>"
    else:
        body = nodata_block()
    cite = citation_line(record, atlas)
    return f"<li>{label}{evidence_link(eid, atlas, page)}{body}{cite}</li>"


def lever_parts(lever, atlas, page):
    values = [f"<code>{esc(v)}</code>" for v in as_list(lever.get("values"))]
    by_model = lever.get("values_by_model")
    if isinstance(by_model, dict):
        for model in sorted(by_model):
            joined = ", ".join(f"<code>{esc(v)}</code>" for v in as_list(by_model[model]))
            values.append(f"{esc(model)}: {joined}")
    unread = [f"<code>{esc(m)}</code> [unverified]" for m in as_list(lever.get("unread_models"))]
    citations = [evidence_link(e, atlas, page) for e in as_list(lever.get("evidence"))]
    literal = lever.get("literal")
    default = lever.get("default")
    model = lever.get("model")
    return {
        "row": f"<code>{esc(lever.get('row'))}</code>",
        "kind": f"<code>{esc(lever.get('location_kind'))}</code>",
        "literal": f"<code>{esc(literal)}</code>" if literal else NODATA_INLINE,
        "scope": esc(lever.get("scope")) if lever.get("scope") else NODATA_INLINE,
        "values": "<br>".join(values + unread) if values or unread else NODATA_INLINE,
        "default": f"<code>{esc(default)}</code>" if default else NODATA_INLINE,
        "model": esc(model) if model else "all",
        "state": state_mark(lever),
        "citation": "<br>".join(citations) if citations else NODATA_INLINE,
    }


