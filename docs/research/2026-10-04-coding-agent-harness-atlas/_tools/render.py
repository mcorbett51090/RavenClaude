    out = [f'<div class="cell {cls}" id="{esc(clean(cell_id))}">']
    if show_name:
        out.append(heading(4, atlas.surface_name(sid)))
    if cell is None:
        out.append(f'<p class="st">{NODATA_MARK}</p>')
    else:
        out.append(f'<p class="st">{state_mark(cell, with_marker=True)}</p>')
        if cell.get("value"):
            out.append(f"<p><strong>Value:</strong> {esc(cell.get('value'))}</p>")
        if cell.get("limitation"):
            out.append(f"<p><strong>Limitation:</strong> {esc(cell.get('limitation'))}</p>")
        scope = [clean(s) for s in as_list(cell.get("surface_scope"))]
        if scope:
            out.append(f"<p><strong>Scope:</strong> {esc(', '.join(scope))}</p>")
        if cell.get("drifted"):
            out.append('<p><strong>Drifted:</strong> <span class="w">drifted</span></p>')
        if isinstance(cell.get("sweep_report"), dict):
            out.append(f'<p class="muted">{esc(sweep_text(cell["sweep_report"]))}</p>')
        shown, hidden = split_refs(cell_evidence_refs(cell))
        if shown:
            items = "".join(evidence_block(e, r, atlas, page) for r, e in shown)
            if hidden:
                more = local_link(
                    page, f"sources/{sid}.html", f"{len(hidden)} more on the sources page", cell_id
                )
                items += f"<li>{more}</li>"
            out.append(f"<p><strong>Evidence:</strong></p><ul>{items}</ul>")
    levers = atlas.levers_by_cell.get((sid, row_id), [])
    if levers:
        out.append("<p><strong>Lever locations:</strong></p>")
        out.append("<ul>" + "".join(lever_line(lv, atlas, page) for lv in levers) + "</ul>")
    entries = atlas.register_by_cell.get(cell_id, [])
