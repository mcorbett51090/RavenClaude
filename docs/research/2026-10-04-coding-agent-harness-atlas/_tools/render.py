def cell_evidence_refs(cell):
    seen = []
    refs = [(None, e) for e in as_list(cell.get("evidence"))]
    refs += [(label, cell.get(key)) for key, label in EVIDENCE_ROLES if cell.get(key)]
    out = []
    for role, eid in refs:
        if eid not in seen:
            seen.append(eid)
            out.append((role, eid))
    return out


def harness_cell(atlas, sid, row_id, page, show_name):
    cell = atlas.cells.get((sid, row_id))
