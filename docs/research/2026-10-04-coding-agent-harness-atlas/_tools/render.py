def marker_text(cell):
    """``[unverified: <reason>; settles by <settles_by>]`` from a cell's marker and settles_by."""
    settles = clean(cell.get("settles_by")).strip() or "re-extraction"
    marker = clean(cell.get("marker")).strip()
    if marker.startswith("[unverified") and marker.endswith("]"):
        return marker
    reason = marker or "no verified evidence record"
    return f"[unverified: {reason}; settles by {settles}]"


def state_mark(item, with_marker=False):
    word = STATE_INFO[item["state"]][1]
    out = f'{glyph(item["state"])} <span class="w">{esc(word)}</span>'
    if item["verification"] == "unverified":
        out += (
            ' <span class="uv" role="img" aria-label="unverified">!</span>'
            ' <span class="w">unverified</span>'
        )
        if with_marker:
            out += f' <span class="marker">{esc(marker_text(item))}</span>'
    return out


