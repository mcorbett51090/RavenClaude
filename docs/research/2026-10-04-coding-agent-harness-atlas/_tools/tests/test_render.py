def write_data(root, data, raw=None):
    """Write ``data`` (see fixture()) under ``root``/data with the real facets and surfaces."""
    base = Path(root) / "data"
    base.mkdir(parents=True, exist_ok=True)
    for name in ("facets.json", "surfaces.json"):
        shutil.copy(DATA_DIR / name, base / name)
    for sid, items in data.get("cells", {}).items():
        dump_json(base / "cells" / f"{sid}.json", {"surface": sid, "cells": items})
    for sid, items in data.get("evidence", {}).items():
        dump_json(base / "evidence" / f"{sid}.json", {"surface": sid, "evidence": items})
    for name in ("levers", "register", "snapshot"):
        if name in data:
            dump_json(base / f"{name}.json", data[name])
    for name, text in (raw or {}).items():
        (base / name).parent.mkdir(parents=True, exist_ok=True)
        (base / name).write_text(text, encoding="ascii")
    return base


class Scan(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.tags = Counter()
        self.ids = []
        self.links = []
        self.attr_names = set()
        self.scripts = []
        self.csp = None
        self.lang = None
        self.table_captions = []
        self._in_script = False
        self._tables = []

    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)
        self.tags[tag] += 1
        self.attr_names.update(name for name, _ in attrs)
        if "id" in attributes:
            self.ids.append(attributes["id"])
        for name in ("href", "src"):
            if name in attributes:
                self.links.append((name, attributes[name]))
        if tag == "html":
            self.lang = attributes.get("lang")
        if tag == "meta" and attributes.get("http-equiv") == "Content-Security-Policy":
            self.csp = attributes.get("content")
        if tag == "script":
            self._in_script = True
            self.scripts.append("")
        if tag == "table":
            self._tables.append(False)
        if tag == "caption" and self._tables:
            self._tables[-1] = True

    def handle_endtag(self, tag):
        if tag == "script":
            self._in_script = False
        if tag == "table":
            self.table_captions.append(self._tables.pop())

    def handle_data(self, data):
        if self._in_script:
            self.scripts[-1] += data


def scan(text):
    parser = Scan()
    parser.feed(text)
    parser.close()
    return parser


def render_pages(data_dir):
    return render.render_all(data_dir)


def read_tree(root):
    root = Path(root)
    return {
        p.relative_to(root).as_posix(): p.read_bytes()
        for p in sorted(root.rglob("*"))
        if p.is_file()
    }


def run_cli(args, env=None):
    environment = dict(os.environ)
    environment["ATLAS_TEST_ALLOW_ANY_TREE"] = "1"
    environment.update(env or {})
    return subprocess.run(
        [sys.executable, str(RENDER_PY), *args],
        capture_output=True,
        text=True,
        env=environment,
        check=False,
    )


def run_main(args):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = render.main(args)
    return code, out.getvalue(), err.getvalue()


