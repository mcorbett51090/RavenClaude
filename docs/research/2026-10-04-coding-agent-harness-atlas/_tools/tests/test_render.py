class PageSetTests(RenderTestCase):
    def test_every_page_named_in_the_table_is_written(self):
        code, _, err = run_main(["--data-dir", str(self.data_dir), "--out", str(self.out_dir)])
        self.assertEqual(code, 0, err)
        self.assertEqual(sorted(read_tree(self.out_dir)), sorted(EXPECTED_PAGES))

    def test_seven_harness_pages_and_eight_source_pages(self):
        pages = self.pages()
        self.assertEqual(
            sorted(p for p in pages if p.startswith("harness/")),
            sorted(f"harness/{p}.html" for p in PRODUCTS),
        )
        self.assertEqual(len(PRODUCTS), 7)
        self.assertEqual(
            sorted(p for p in pages if p.startswith("sources/")),
            sorted(f"sources/{s}.html" for s in SURFACE_IDS),
        )
        self.assertEqual(len(SURFACE_IDS), 8)

    def test_every_page_is_reachable_from_the_index(self):
        pages = self.pages()
        seen, queue = {"index.html"}, ["index.html"]
        while queue:
            page = queue.pop()
            for _, link in scan(pages[page]).links:
                if "://" in link:
                    continue
                target = posixpath.normpath(
                    posixpath.join(posixpath.dirname(page), link.split("#")[0])
                )
                if link.split("#")[0] and target in pages and target not in seen:
                    seen.add(target)
                    queue.append(target)
        self.assertEqual(sorted(seen), sorted(pages))

    def test_defaults_render_the_real_data_directory(self):
        code, _, err = run_main(["--out", str(self.out_dir)])
        self.assertEqual(code, 0, err)
        self.assertEqual(sorted(read_tree(self.out_dir)), sorted(EXPECTED_PAGES))

    def test_a_nearly_empty_data_directory_renders_with_no_data_cells(self):
        empty = write_data(self.root / "empty", {})
        pages = render_pages(empty)
        self.assertEqual(sorted(pages), sorted(EXPECTED_PAGES))
        self.assertIn("no data", pages["matrix.html"])
        self.assertIn("no data", pages["harness/cursor.html"])
        self.assertIn("no data", pages["sources/cursor.html"])
        self.assertIn("no data", pages["register.html"])
        self.assertIn("0 of 8 (flagged: matrix rows pending for claude-code,", pages["index.html"])

    def test_missing_required_file_and_malformed_json_exit_nonzero_naming_the_file(self):
        (self.data_dir / "surfaces.json").unlink()
        code, _, err = run_main(["--data-dir", str(self.data_dir), "--out", str(self.out_dir)])
        self.assertEqual(code, 2)
        self.assertIn("surfaces.json", err)
        shutil.copy(DATA_DIR / "surfaces.json", self.data_dir / "surfaces.json")
        (self.data_dir / "register.json").write_text("{not json", encoding="utf-8")
        code, _, err = run_main(["--data-dir", str(self.data_dir), "--out", str(self.out_dir)])
        self.assertEqual(code, 2)
        self.assertIn("register.json", err)

    def test_an_unknown_state_is_an_error_not_a_silent_default(self):
        data = fixture()
        data["cells"]["claude-code"][0]["state"] = "mostly"
        broken = write_data(self.root / "broken", data)
