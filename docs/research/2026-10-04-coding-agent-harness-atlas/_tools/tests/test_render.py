class SelfContainedTests(RenderTestCase):
    def test_no_remote_fetch_of_any_kind(self):
        for path, text in self.pages().items():
            parsed = scan(text)
            self.assertNotIn("src", [name for name, _ in parsed.links], path)
            for banned in (
                "@import",
                "url(",
                "<link",
                "<img",
                "<iframe",
                "<object",
                "<embed",
                "<form",
            ):
                self.assertNotIn(banned, text, f"{path}: {banned}")
            self.assertNotIn("@font-face", text, path)
            self.assertNotIn("fonts.googleapis", text, path)

    def test_csp_meta_on_every_page_matches_the_inline_script_hash(self):
        with_script = 0
        for path, text in self.pages().items():
            parsed = scan(text)
            self.assertIsNotNone(parsed.csp, path)
            if parsed.scripts:
                with_script += 1
                digest = base64.b64encode(hashlib.sha256(parsed.scripts[0].encode()).digest())
                self.assertEqual(
                    parsed.csp,
                    "default-src 'none'; style-src 'unsafe-inline'; "
                    f"script-src 'sha256-{digest.decode()}'; img-src data:; "
                    "base-uri 'none'; form-action 'none'",
                    path,
                )
            else:
                self.assertEqual(parsed.csp, BASE_CSP, path)
                self.assertNotIn("script-src", parsed.csp)
        self.assertGreater(with_script, 0)

    def test_script_is_present_exactly_when_the_page_has_dates(self):
        for path, text in self.pages().items():
            self.assertEqual("<time " in text, "<script>" in text, path)
        pages = self.pages()
        self.assertIn("<script>", pages["harness/claude-code.html"])
        self.assertNotIn("<script>", pages["matrix.html"])

    def test_the_script_only_adds_an_age_label(self):
        script = render.AGE_SCRIPT
        for word in ("fresh", "ageing", "stale", "30", "90"):
            self.assertIn(word, script)
        for banned in ("fetch(", "XMLHttpRequest", "innerHTML", "eval(", "document.write", "src"):
            self.assertNotIn(banned, script)

    def test_every_page_reads_without_javascript(self):
        # the dates are in the static markup, and the matrix is a plain table
        pages = self.pages()
        self.assertIn('<time datetime="2026-10-04">2026-10-04</time>', pages["index.html"])
        self.assertEqual(
            pages["matrix.html"].count("<tr id="), len(set(render.Atlas(self.data_dir).row_ids))
        )

    def test_css_is_small(self):
        self.assertLess(len(render.CSS.encode("utf-8")), 6 * 1024)


